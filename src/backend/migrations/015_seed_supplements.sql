-- Audit the whole catalog before any insert, including aliases and diacritics.
CREATE OR REPLACE FUNCTION pg_temp.supplement_name(value TEXT) RETURNS TEXT
LANGUAGE sql STABLE STRICT AS $$
    SELECT btrim(regexp_replace(lower(unaccent(value)), '[^a-z0-9]+', ' ', 'g'))
$$;
CREATE TEMP TABLE supplement_catalog_names ON COMMIT DROP AS
SELECT DISTINCT h.id, pg_temp.supplement_name(n.name) AS name
FROM herbs h
CROSS JOIN LATERAL (
    SELECT unnest(ARRAY[h.ro, h.en, h.latin]) AS name
    UNION ALL SELECT a.name FROM herb_aliases a WHERE a.herb_id = h.id
) n
WHERE n.name IS NOT NULL AND btrim(n.name) <> '';
CREATE INDEX ON supplement_catalog_names (name);

DO $$
DECLARE
    candidate RECORD;
    matched_species TEXT[];
    matching_ids BIGINT[];
BEGIN
    FOR candidate IN SELECT * FROM supplement_candidates ORDER BY ro LOOP
        SELECT array_agg(DISTINCT n.id ORDER BY n.id) INTO matching_ids
        FROM supplement_catalog_names n
        WHERE n.name IN (
            pg_temp.supplement_name(candidate.ro), pg_temp.supplement_name(candidate.en)
        );
        IF candidate.existing_species IS NOT NULL THEN
            SELECT array_agg(h.latin ORDER BY h.latin) INTO matched_species
            FROM herbs h WHERE h.id = ANY(matching_ids);
            IF matched_species IS DISTINCT FROM candidate.existing_species THEN
                RAISE EXCEPTION 'Supplement identity conflict for reused label: %', candidate.ro;
            END IF;
        ELSIF matching_ids IS NOT NULL THEN
            -- Exact agreement is the only idempotent replay. Never hide conflicting data.
            IF cardinality(matching_ids) <> 1 OR NOT EXISTS (
                SELECT 1 FROM herbs h WHERE h.id = matching_ids[1]
                AND h.ro = candidate.ro AND h.en = candidate.en
                AND h.family = candidate.family AND h.latin IS NULL
            ) THEN
                RAISE EXCEPTION 'Supplement name/alias collision: % (catalog IDs %)',
                    candidate.ro, matching_ids;
            END IF;
        END IF;
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM herbs WHERE latin = 'thuja occidentalis'
                   AND ro = 'tuia' AND family = 'cupressaceae') THEN
        RAISE EXCEPTION 'Thuja occidentalis identity missing or conflicting';
    END IF;
    IF EXISTS (
        SELECT 1 FROM supplement_catalog_names n JOIN herbs h ON h.id = n.id
        WHERE n.name = 'thuya occidentalis' AND h.latin IS DISTINCT FROM 'thuja occidentalis'
    ) THEN
        RAISE EXCEPTION 'Thuya occidentalis spelling belongs to another catalog entry';
    END IF;
END $$;

INSERT INTO herbs (ro, en, family, latin)
SELECT c.ro, c.en, c.family, NULL
FROM supplement_candidates c
WHERE c.existing_species IS NULL
AND NOT EXISTS (
    SELECT 1 FROM herbs h WHERE lower(btrim(h.ro)) = lower(btrim(c.ro))
)
ORDER BY c.ro COLLATE "C";

INSERT INTO herb_aliases (herb_id, kind, name)
SELECT h.id, a.kind, a.name
FROM herbs h
CROSS JOIN (VALUES
    ('ro_regional', 'arborele vietii'),
    ('latin_synonyms', 'thuya occidentalis')
) AS a(kind, name)
WHERE h.latin = 'thuja occidentalis'
AND NOT EXISTS (
    SELECT 1 FROM herb_aliases existing
    WHERE existing.herb_id = h.id AND existing.kind = a.kind AND existing.name = a.name
);
